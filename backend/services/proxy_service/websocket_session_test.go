func TestBuildWebSocketHeadersPreservesOrderedFieldSemantics(t *testing.T) {
	t.Parallel()

	headers, order, err := buildWebSocketHeaders(
		[]HTTPHeaderField{
			{Name: " X-Request-Last ", Value: "last-1"},
			{Name: "X-Request-Last", Value: "last-2"},
			{Name: "x-request-first", Value: "first"},
			{Name: "Connection", Value: "close"},
			{Name: "", Value: "ignored"},
		},
	)
	if err != nil {
		t.Fatal(err)
	}

	wantHeaders := http.Header{
		"X-Request-Last":  {"last-1", "last-2"},
		"x-request-first": {"first"},
	}
	if !reflect.DeepEqual(headers, wantHeaders) {
		t.Fatalf("headers:\n got %#v\nwant %#v", headers, wantHeaders)
	}
	wantOrder := []string{
		"Host",
		"Upgrade",
		"Connection",
		"Sec-WebSocket-Key",
		"Sec-WebSocket-Version",
		"X-Request-Last",
		"x-request-first",
	}
	if !reflect.DeepEqual(order.Headers, wantOrder) {
		t.Fatalf("header order = %#v, want %#v", order.Headers, wantOrder)
	}
}

func TestBuildWebSocketHeadersRejectsUnsafeOrUnrepresentableFields(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name   string
		fields []HTTPHeaderField
		want   string
	}{
		{
			name: "pseudo header",
			fields: []HTTPHeaderField{
				{Name: ":status", Value: "200"},
			},
			want: "generated by the backend",
		},
		{
			name: "invalid token name",
			fields: []HTTPHeaderField{
				{Name: "Bad Header", Value: "value"},
			},
			want: "invalid HTTP header name",
		},
		{
			name: "invalid value",
			fields: []HTTPHeaderField{
				{Name: "X-Test", Value: "one\r\ntwo"},
			},
			want: "invalid value",
		},
		{
			name: "interleaved occurrences",
			fields: []HTTPHeaderField{
				{Name: "X-A", Value: "first"},
				{Name: "X-B", Value: "middle"},
				{Name: "X-A", Value: "last"},
			},
			want: "cannot preserve interleaved",
		},
		{
			name: "per occurrence casing",
			fields: []HTTPHeaderField{
				{Name: "X-A", Value: "first"},
				{Name: "x-a", Value: "last"},
			},
			want: "cannot preserve per-occurrence casing",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, _, err := buildWebSocketHeaders(tt.fields)
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("error = %v, want substring %q", err, tt.want)
			}
		})
	}
}

func TestWebSocketSessionPreservesHandshakeHeaderFields(t *testing.T) {
	requestFieldsCh := make(chan []HTTPHeaderField, 1)
	serverErrCh := make(chan error, 1)
	responseOrder := []string{
		"X-Response-Last",
		"sec-websocket-accept",
		"upgrade",
		"connection",
		"x-response-first",
	}
	upgrader := websocket.Upgrader{
		ResponseHeaderOrder: http.HeaderOrder{Headers: responseOrder},
	}
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		fields, _ := initialHeaderFields(http.RequestHeaderBlocks(r))
		requestFieldsCh <- fields
		conn, err := upgrader.Upgrade(w, r, http.Header{
			"X-Response-Last":  {"last"},
			"x-response-first": {"first"},
		})
		if err != nil {
			serverErrCh <- err
			return
		}
		defer conn.Close()
		for {
			if _, _, err := conn.ReadMessage(); err != nil {
				serverErrCh <- nil
				return
			}
		}
	}))
	defer server.Close()

	svc := newTestProxyService(t, nil)
	connectResp, err := svc.ConnectWebSocket(context.Background(), WebSocketConnectRequest{
		URL: strings.Replace(server.URL, "http://", "ws://", 1),
		HeaderFields: []HTTPHeaderField{
			{Name: "X-Request-Last", Value: "last-1"},
			{Name: "X-Request-Last", Value: "last-2"},
			{Name: "x-request-first", Value: "first"},
			{Name: "Connection", Value: "close"},
		},
	})
	if err != nil {
		t.Fatalf("connect failed: %v", err)
	}

	requestFields := <-requestFieldsCh
	customRequestFields := make([]HTTPHeaderField, 0, 3)
	requestUserAgent := ""
	for _, field := range requestFields {
		if strings.HasPrefix(strings.ToLower(field.Name), "x-request-") {
			customRequestFields = append(customRequestFields, field)
		}
		if strings.EqualFold(field.Name, "User-Agent") {
			requestUserAgent = field.Value
		}
	}
	wantRequestFields := []HTTPHeaderField{
		{Name: "X-Request-Last", Value: "last-1"},
		{Name: "X-Request-Last", Value: "last-2"},
		{Name: "x-request-first", Value: "first"},
	}
	if !reflect.DeepEqual(customRequestFields, wantRequestFields) {
		t.Errorf("request fields:\n got %#v\nwant %#v", customRequestFields, wantRequestFields)
	}
	if requestUserAgent != UserAgentHeader {
		t.Errorf("request User-Agent = %q, want %q", requestUserAgent, UserAgentHeader)
	}
	var responseLastValue string
	for _, field := range connectResp.HeaderFields {
		if strings.EqualFold(field.Name, "X-Response-Last") {
			responseLastValue = field.Value
			break
		}
	}
	if responseLastValue != "last" {
		t.Errorf("ordered response header value = %q, want last", responseLastValue)
	}
	wantResponseNames := make([]string, len(responseOrder))
	for index, name := range responseOrder {
		wantResponseNames[index] = strings.ToLower(name)
	}
	gotResponseNames := make([]string, len(connectResp.HeaderFields))
	for index, field := range connectResp.HeaderFields {
		gotResponseNames[index] = strings.ToLower(field.Name)
	}
	if !reflect.DeepEqual(gotResponseNames, wantResponseNames) {
		t.Errorf("response header order = %#v, want %#v", gotResponseNames, wantResponseNames)
	}
	if connectResp.HeadersTruncated {
		t.Error("successful WebSocket handshake headers unexpectedly truncated")
	}

	if err := svc.DisconnectWebSocket(connectResp.SessionID); err != nil {
		t.Fatalf("disconnect failed: %v", err)
	}
	select {
	case err := <-serverErrCh:
		if err != nil {
			t.Fatalf("server WebSocket failed: %v", err)
		}
	case <-time.After(2 * time.Second):
		t.Fatal("timed out waiting for WebSocket server to close")
	}
}

func TestWebSocketHTTPRequestSessionLifecycle(t *testing.T) {
	t.Parallel()

	upgrader := websocket.Upgrader{}
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		conn, err := upgrader.Upgrade(w, r, nil)
		if err != nil {
			t.Fatalf("upgrade failed: %v", err)
		}
		defer conn.Close()

		for {
			msgType, payload, err := conn.ReadMessage()
			if err != nil {
				return
			}
			if err := conn.WriteMessage(msgType, payload); err != nil {
				t.Fatalf("write failed: %v", err)
			}
		}
	}))
	defer server.Close()

	eventCh := make(chan WebSocketSessionEvent, 8)
	svc := newTestProxyService(t, nil)
	svc.emitWebSocketSessionEventHook = func(event WebSocketSessionEvent) {
		eventCh <- event
	}

	connectCallCtx, cancelConnectCall := context.WithCancel(context.Background())
	connectResp, err := svc.ConnectWebSocket(connectCallCtx, WebSocketConnectRequest{
		URL: strings.Replace(server.URL, "http://", "ws://", 1),
	})
	if err != nil {
		t.Fatalf("connect failed: %v", err)
	}
	if connectResp.SessionID == "" {
		t.Fatal("expected session id")
	}
	if connectResp.StatusCode != http.StatusSwitchingProtocols {
		t.Fatalf("status code = %d, want %d", connectResp.StatusCode, http.StatusSwitchingProtocols)
	}
	if connectResp.Protocol == "" {
		t.Fatal("expected handshake protocol")
	}
	if len(connectResp.HeaderFields) == 0 {
		t.Fatal("expected handshake response headers")
	}
	cancelConnectCall()

	waitForRequestEvent(t, eventCh, func(event WebSocketSessionEvent) bool {
		return event.SessionID == connectResp.SessionID && event.EventType == "connected"
	})

	if err := svc.SendWebSocketMessage(WebSocketSendRequest{
		SessionID: connectResp.SessionID,
		MsgType:   "text",
		Text:      "hello",
	}); err != nil {
		t.Fatalf("send failed: %v", err)
	}

	var sendEvent, receiveEvent WebSocketSessionEvent
	for sendEvent.Message == nil || receiveEvent.Message == nil {
		event := waitForRequestEvent(t, eventCh, func(event WebSocketSessionEvent) bool {
			return event.SessionID == connectResp.SessionID &&
				event.EventType == "message" &&
				event.Message != nil
		})
		if event.Message.Direction == "send" {
			sendEvent = event
		} else if event.Message.Direction == "receive" {
			receiveEvent = event
		}
	}
	if sendEvent.Message.Data != "hello" {
		t.Fatalf("send event payload = %q, want hello", sendEvent.Message.Data)
	}
	if receiveEvent.Message.Data != "hello" {
		t.Fatalf("receive event payload = %q, want hello", receiveEvent.Message.Data)
	}

	if err := svc.DisconnectWebSocket(connectResp.SessionID); err != nil {
		t.Fatalf("disconnect failed: %v", err)
	}

	waitForRequestEvent(t, eventCh, func(event WebSocketSessionEvent) bool {
		return event.SessionID == connectResp.SessionID && event.EventType == "closed"
	})

	if _, ok := svc.webSocketSessions.Load(connectResp.SessionID); ok {
		t.Fatal("session should be removed after disconnect")
	}
}

func TestWebSocketSessionConnectCancellation(t *testing.T) {
	requestStarted := make(chan struct{})
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		close(requestStarted)
		<-r.Context().Done()
	}))
	defer server.Close()

	svc := newTestProxyService(t, nil)
	t.Cleanup(svc.baseCancel)
	callCtx, cancelCall := context.WithCancel(context.Background())
	resultCh := make(chan error, 1)
	go func() {
		_, err := svc.ConnectWebSocket(callCtx, WebSocketConnectRequest{
			URL: strings.Replace(server.URL, "http://", "ws://", 1),
		})
		resultCh <- err
	}()

	select {
	case <-requestStarted:
	case <-time.After(2 * time.Second):
		cancelCall()
		t.Fatal("timed out waiting for WebSocket session handshake")
	}
	cancelCall()

	select {
	case err := <-resultCh:
		if !errors.Is(err, context.Canceled) {
			t.Fatalf("ConnectWebSocket error = %v, want context canceled", err)
		}
	case <-time.After(2 * time.Second):
		t.Fatal("WebSocket session handshake did not stop after cancellation")
	}

	var sessionCount int
	svc.webSocketSessions.Range(func(_, _ any) bool {
		sessionCount++
		return true
	})
	if sessionCount != 0 {
		t.Fatalf("cancelled handshake left %d WebSocket sessions", sessionCount)
	}
}

func TestWebSocketSessionHandshakeTimeout(t *testing.T) {
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		<-r.Context().Done()
	}))
	defer server.Close()

	svc := newTestProxyService(t, nil)
	t.Cleanup(svc.baseCancel)
	started := time.Now()
	_, err := svc.ConnectWebSocket(context.Background(), WebSocketConnectRequest{
		URL:       strings.Replace(server.URL, "http://", "ws://", 1),
		TimeoutMs: 50,
	})
	if !errors.Is(err, context.DeadlineExceeded) {
		t.Fatalf("ConnectWebSocket error = %v, want context deadline exceeded", err)
	}
	if elapsed := time.Since(started); elapsed > time.Second {
		t.Fatalf("WebSocket session handshake timeout took %s", elapsed)
	}
}

