func TestWebSocketHTTPRequestSessionRemoteCloseEmitsClosedEvent(t *testing.T) {
	t.Parallel()

	upgrader := websocket.Upgrader{}
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		conn, err := upgrader.Upgrade(w, r, nil)
		if err != nil {
			t.Fatalf("upgrade failed: %v", err)
		}
		defer conn.Close()

		time.Sleep(100 * time.Millisecond)
		_ = conn.WriteMessage(
			websocket.CloseMessage,
			websocket.FormatCloseMessage(websocket.CloseGoingAway, "server closing"),
		)
	}))
	defer server.Close()

	eventCh := make(chan WebSocketSessionEvent, 8)
	svc := newTestProxyService(t, nil)
	svc.emitWebSocketSessionEventHook = func(event WebSocketSessionEvent) {
		eventCh <- event
	}

	connectResp, err := svc.ConnectWebSocket(context.Background(), WebSocketConnectRequest{
		URL: strings.Replace(server.URL, "http://", "ws://", 1),
	})
	if err != nil {
		t.Fatalf("connect failed: %v", err)
	}

	waitForRequestEvent(t, eventCh, func(event WebSocketSessionEvent) bool {
		return event.SessionID == connectResp.SessionID && event.EventType == "connected"
	})

	terminalEvent := waitForRequestEvent(t, eventCh, func(event WebSocketSessionEvent) bool {
		return event.SessionID == connectResp.SessionID &&
			(event.EventType == "closed" || event.EventType == "error")
	})
	if terminalEvent.Status != "closed" && terminalEvent.Status != "error" {
		t.Fatalf("unexpected terminal status %q", terminalEvent.Status)
	}

	if _, ok := svc.webSocketSessions.Load(connectResp.SessionID); ok {
		t.Fatal("session should be removed after remote close")
	}
}

func waitForRequestEvent(
	t *testing.T,
	eventCh <-chan WebSocketSessionEvent,
	match func(WebSocketSessionEvent) bool,
) WebSocketSessionEvent {
	t.Helper()

	timeout := time.NewTimer(3 * time.Second)
	defer timeout.Stop()

	for {
		select {
		case event := <-eventCh:
			if match(event) {
				return event
			}
		case <-timeout.C:
			t.Fatal("timed out waiting for WebSocket session event")
		}
	}
}
