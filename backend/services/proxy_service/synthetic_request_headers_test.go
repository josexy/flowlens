func TestReconcileSyntheticBodyFraming(t *testing.T) {
	fields := []HTTPHeaderField{
		{Name: "X-Before", Value: "one"},
		{Name: "cOnTeNt-LeNgTh", Value: "999"},
		{Name: "X-Middle", Value: "two"},
		{Name: "Transfer-Encoding", Value: "gzip"},
		{Name: "X-After", Value: "three"},
	}
	tests := []struct {
		name          string
		protocol      SendRequestProtocol
		contentLength int64
		hasBody       bool
		want          []HTTPHeaderField
	}{
		{
			name:          "HTTP1 fixed length",
			protocol:      SendRequestProtocolHTTP1,
			contentLength: 4,
			hasBody:       true,
			want: []HTTPHeaderField{
				{Name: "X-Before", Value: "one"},
				{Name: "cOnTeNt-LeNgTh", Value: "4"},
				{Name: "X-Middle", Value: "two"},
				{Name: "X-After", Value: "three"},
			},
		},
		{
			name:          "HTTP1 streaming",
			protocol:      SendRequestProtocolHTTP1,
			contentLength: -1,
			hasBody:       true,
			want: []HTTPHeaderField{
				{Name: "X-Before", Value: "one"},
				{Name: "Transfer-Encoding", Value: "chunked"},
				{Name: "X-Middle", Value: "two"},
				{Name: "X-After", Value: "three"},
			},
		},
		{
			name:          "HTTP2 fixed length",
			protocol:      SendRequestProtocolHTTP2,
			contentLength: 4,
			hasBody:       true,
			want: []HTTPHeaderField{
				{Name: "X-Before", Value: "one"},
				{Name: "content-length", Value: "4"},
				{Name: "X-Middle", Value: "two"},
				{Name: "X-After", Value: "three"},
			},
		},
		{
			name:          "HTTP2 streaming",
			protocol:      SendRequestProtocolHTTP2,
			contentLength: -1,
			hasBody:       true,
			want: []HTTPHeaderField{
				{Name: "X-Before", Value: "one"},
				{Name: "X-Middle", Value: "two"},
				{Name: "X-After", Value: "three"},
			},
		},
		{
			name:          "no body",
			protocol:      SendRequestProtocolHTTP1,
			contentLength: 0,
			hasBody:       false,
			want: []HTTPHeaderField{
				{Name: "X-Before", Value: "one"},
				{Name: "X-Middle", Value: "two"},
				{Name: "X-After", Value: "three"},
			},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := reconcileSyntheticBodyFraming(fields, tt.protocol, tt.contentLength, tt.hasBody)
			if !reflect.DeepEqual(got, tt.want) {
				t.Fatalf("framing fields:\n got %#v\nwant %#v", got, tt.want)
			}
		})
	}
}

