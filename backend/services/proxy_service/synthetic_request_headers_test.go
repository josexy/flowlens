func startRawHTTP1CaptureServer(t *testing.T, response string) (string, <-chan string) {
	t.Helper()
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = listener.Close() })
	wireCh := make(chan string, 1)
	go func() {
		conn, acceptErr := listener.Accept()
		if acceptErr != nil {
			return
		}
		defer conn.Close()
		_ = conn.SetDeadline(time.Now().Add(5 * time.Second))
		reader := bufio.NewReader(conn)
		var wire strings.Builder
		for {
			line, readErr := reader.ReadString('\n')
			if readErr != nil {
				return
			}
			wire.WriteString(line)
			if line == "\r\n" {
				break
			}
		}
		wireCh <- wire.String()
		_, _ = io.WriteString(conn, response)
	}()
	return "http://" + listener.Addr().String(), wireCh
}

func requestHeaderLines(wire string) []string {
	lines := strings.Split(wire, "\r\n")
	if len(lines) <= 2 {
		return nil
	}
	return lines[1 : len(lines)-2]
}
